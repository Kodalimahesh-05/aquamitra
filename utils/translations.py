def t(key: str, lang: str = "en") -> str:
    """
    Translates a key into the selected language (default: 'en').
    Falls back to English if key is missing in Telugu.
    """
    lang_dict = TRANSLATIONS.get(lang, TRANSLATIONS["en"])
    return lang_dict.get(key, TRANSLATIONS["en"].get(key, key))


def tv(val, lang: str = "en") -> str:
    """
    Translates domain option/status values cleanly when lang == 'te',
    preserving original value in English or if no mapping exists.
    """
    if val is None:
        return ""
    s = str(val)
    if lang != "te":
        return s
    return VALUE_TRANSLATIONS_TE.get(s, s)


def rename_df_for_display(df, lang: str = "en"):
    """
    Returns a display copy of a DataFrame with Telugu column headers when lang == 'te'.
    Safe no-op in English or on empty DataFrames.
    """
    if df is None or lang != "te" or df.empty:
        return df
    return df.rename(columns={col: COLUMN_LABELS_TE.get(col, col) for col in df.columns})

